#!/usr/bin/env python3
"""
Storage Format Benchmark for Sequence Training Data

Comprehensive benchmark comparing Riegeli, TFRecord, HDF5, Parquet, and Pickle
for storing sequence-based training data generated by TimeSeriesSequenceTrainingGenerator.
"""

import os
import sys
import time
import asyncio
import logging
import tempfile
from pathlib import Path
from datetime import date, datetime
from typing import List, Dict, Any
from dataclasses import dataclass
import json

# Add src to path
sys.path.insert(0, str(Path(__file__).parent.parent.parent / "src"))

from config.environment import Environment
from ml.training_data.timeseries_sequence_training_generator import (
    TimeSeriesSequenceTrainingGenerator, 
    TrainingDataConfig,
    SequenceTrainingExample
)
from ml.storage.sequence_storage_manager import SequenceStorageManager, StorageConfig
from state.universe_state_manager import UniverseStateManager


@dataclass
class BenchmarkResult:
    """Results from a storage format benchmark."""
    format_name: str
    write_time_seconds: float
    read_time_seconds: float
    file_size_bytes: int
    compression_ratio: float
    examples_per_second_write: float
    examples_per_second_read: float
    error: str = ""


class StorageFormatBenchmark:
    """Benchmark different storage formats for sequence training data."""
    
    def __init__(self, debug: bool = False):
        self.debug = debug
        self.setup_logging()
        self.logger = logging.getLogger(__name__)
        
        # Initialize components
        self.env = Environment()
        self.config = TrainingDataConfig(
            base_interval_minutes=1,
            training_interval_minutes=60,
            sequence_lengths={'5m': 10, '15m': 8, '1h': 6, '1d': 5},  # Smaller for benchmarking
            prediction_horizons={'1h': 3, '1d': 2}
        )
        
        self.universe_manager = UniverseStateManager(env=self.env)
        self.training_generator = TimeSeriesSequenceTrainingGenerator(
            env=self.env,
            config=self.config,
            universe_manager=self.universe_manager
        )
    
    def setup_logging(self):
        """Setup logging configuration."""
        level = logging.DEBUG if self.debug else logging.INFO
        logging.basicConfig(
            level=level,
            format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
        )
    
    async def generate_sample_data(self, num_examples: int = 100) -> List[SequenceTrainingExample]:
        """Generate sample training data for benchmarking."""
        self.logger.info(f"Generating {num_examples} sample training examples...")
        
        # Use a small date range for consistent testing
        start_date = date(2024, 1, 15)
        end_date = date(2024, 1, 16)
        
        examples = await self.training_generator.generate_training_dataset(
            symbols=['AAPL'],  # Single symbol for consistency
            start_date=start_date,
            end_date=end_date,
            min_examples_per_symbol=min(num_examples, 50)
        )
        
        # Duplicate examples if we need more for benchmarking
        while len(examples) < num_examples:
            examples.extend(examples[:min(num_examples - len(examples), len(examples))])
        
        return examples[:num_examples]
    
    def benchmark_pickle(self, examples: List[SequenceTrainingExample], temp_dir: Path) -> BenchmarkResult:
        """Benchmark Python pickle format."""
        import pickle
        
        file_path = temp_dir / "benchmark_data.pkl"
        
        try:
            # Write benchmark
            start_time = time.time()
            with open(file_path, 'wb') as f:
                pickle.dump(examples, f, protocol=pickle.HIGHEST_PROTOCOL)
            write_time = time.time() - start_time
            
            # Read benchmark
            start_time = time.time()
            with open(file_path, 'rb') as f:
                loaded_examples = pickle.load(f)
            read_time = time.time() - start_time
            
            file_size = file_path.stat().st_size
            
            return BenchmarkResult(
                format_name="Pickle",
                write_time_seconds=write_time,
                read_time_seconds=read_time,
                file_size_bytes=file_size,
                compression_ratio=1.0,  # No compression
                examples_per_second_write=len(examples) / write_time,
                examples_per_second_read=len(loaded_examples) / read_time
            )
            
        except Exception as e:
            return BenchmarkResult(
                format_name="Pickle",
                write_time_seconds=0,
                read_time_seconds=0,
                file_size_bytes=0,
                compression_ratio=0,
                examples_per_second_write=0,
                examples_per_second_read=0,
                error=str(e)
            )
    
    def benchmark_parquet(self, examples: List[SequenceTrainingExample], temp_dir: Path) -> BenchmarkResult:
        """Benchmark Parquet format."""
        import pandas as pd
        
        file_path = temp_dir / "benchmark_data.parquet"
        
        try:
            # Convert examples to DataFrame
            rows = []
            for example in examples:
                row = {
                    'instrument_id': example.instrument_id,
                    'symbol': example.symbol,
                    'prediction_timestamp': example.prediction_timestamp,
                    **example.base_features
                }
                
                # Flatten timeframe features
                for tf, features in example.timeframe_features.items():
                    for feat_name, feat_val in features.items():
                        row[f'tf_{tf}_{feat_name}'] = feat_val
                
                rows.append(row)
            
            df = pd.DataFrame(rows)
            
            # Write benchmark
            start_time = time.time()
            df.to_parquet(file_path, compression='snappy', index=False)
            write_time = time.time() - start_time
            
            # Read benchmark
            start_time = time.time()
            loaded_df = pd.read_parquet(file_path)
            read_time = time.time() - start_time
            
            file_size = file_path.stat().st_size
            
            # Estimate compression ratio
            uncompressed_size = len(df.to_csv(index=False).encode())
            compression_ratio = file_size / uncompressed_size if uncompressed_size > 0 else 1.0
            
            return BenchmarkResult(
                format_name="Parquet",
                write_time_seconds=write_time,
                read_time_seconds=read_time,
                file_size_bytes=file_size,
                compression_ratio=compression_ratio,
                examples_per_second_write=len(examples) / write_time,
                examples_per_second_read=len(loaded_df) / read_time
            )
            
        except Exception as e:
            return BenchmarkResult(
                format_name="Parquet",
                write_time_seconds=0,
                read_time_seconds=0,
                file_size_bytes=0,
                compression_ratio=0,
                examples_per_second_write=0,
                examples_per_second_read=0,
                error=str(e)
            )
    
    def benchmark_hdf5(self, examples: List[SequenceTrainingExample], temp_dir: Path) -> BenchmarkResult:
        """Benchmark HDF5 format."""
        try:
            import h5py
            import pandas as pd
        except ImportError:
            return BenchmarkResult(
                format_name="HDF5",
                write_time_seconds=0,
                read_time_seconds=0,
                file_size_bytes=0,
                compression_ratio=0,
                examples_per_second_write=0,
                examples_per_second_read=0,
                error="h5py not available"
            )
        
        file_path = temp_dir / "benchmark_data.h5"
        
        try:
            # Convert to DataFrame first
            rows = []
            for example in examples:
                row = {
                    'instrument_id': example.instrument_id,
                    'symbol': example.symbol,
                    'prediction_timestamp': example.prediction_timestamp.timestamp(),
                    **example.base_features
                }
                rows.append(row)
            
            df = pd.DataFrame(rows)
            
            # Write benchmark
            start_time = time.time()
            df.to_hdf(file_path, key='training_data', mode='w', complib='zlib', complevel=6)
            write_time = time.time() - start_time
            
            # Read benchmark
            start_time = time.time()
            loaded_df = pd.read_hdf(file_path, key='training_data')
            read_time = time.time() - start_time
            
            file_size = file_path.stat().st_size
            
            # Estimate compression ratio
            uncompressed_size = len(df.to_csv(index=False).encode())
            compression_ratio = file_size / uncompressed_size if uncompressed_size > 0 else 1.0
            
            return BenchmarkResult(
                format_name="HDF5",
                write_time_seconds=write_time,
                read_time_seconds=read_time,
                file_size_bytes=file_size,
                compression_ratio=compression_ratio,
                examples_per_second_write=len(examples) / write_time,
                examples_per_second_read=len(loaded_df) / read_time
            )
            
        except Exception as e:
            return BenchmarkResult(
                format_name="HDF5",
                write_time_seconds=0,
                read_time_seconds=0,
                file_size_bytes=0,
                compression_ratio=0,
                examples_per_second_write=0,
                examples_per_second_read=0,
                error=str(e)
            )
    
    async def benchmark_sequence_storage_manager(self, examples: List[SequenceTrainingExample], 
                                                temp_dir: Path, format_name: str) -> BenchmarkResult:
        """Benchmark SequenceStorageManager with different formats."""
        
        storage_config = StorageConfig(
            primary_format=format_name.lower(),
            compression_level=6,
            chunk_size=len(examples),
            enable_checksums=True
        )
        
        storage_manager = SequenceStorageManager(
            base_path=str(temp_dir / "sequence_storage"),
            config=storage_config
        )
        
        try:
            # Write benchmark
            start_time = time.time()
            batch_id = f"benchmark_{format_name.lower()}"
            save_result = await storage_manager.save_sequence_batch(examples, batch_id)
            write_time = time.time() - start_time
            
            # Read benchmark
            start_time = time.time()
            loaded_examples = await storage_manager.load_sequence_batch(batch_id)
            read_time = time.time() - start_time
            
            # Get file size from save result
            file_size = save_result.get('sequence_stats', {}).get('file_size', 0)
            compression_ratio = save_result.get('sequence_stats', {}).get('compression_ratio', 1.0)
            
            return BenchmarkResult(
                format_name=f"SequenceManager-{format_name}",
                write_time_seconds=write_time,
                read_time_seconds=read_time,
                file_size_bytes=file_size,
                compression_ratio=compression_ratio,
                examples_per_second_write=len(examples) / write_time,
                examples_per_second_read=len(loaded_examples) / read_time
            )
            
        except Exception as e:
            return BenchmarkResult(
                format_name=f"SequenceManager-{format_name}",
                write_time_seconds=0,
                read_time_seconds=0,
                file_size_bytes=0,
                compression_ratio=0,
                examples_per_second_write=0,
                examples_per_second_read=0,
                error=str(e)
            )
    
    async def run_comprehensive_benchmark(self, example_counts: List[int] = [50, 100, 500]) -> Dict[str, List[BenchmarkResult]]:
        """Run comprehensive benchmark across different formats and data sizes."""
        self.logger.info("Starting comprehensive storage format benchmark...")
        
        results = {}
        
        for num_examples in example_counts:
            self.logger.info(f"Benchmarking with {num_examples} examples...")
            
            # Generate sample data
            examples = await self.generate_sample_data(num_examples)
            if not examples:
                self.logger.error(f"Failed to generate {num_examples} examples")
                continue
            
            results[num_examples] = []
            
            # Create temporary directory for this run
            with tempfile.TemporaryDirectory() as temp_dir:
                temp_path = Path(temp_dir)
                
                # Benchmark standard formats
                self.logger.info("Benchmarking Pickle format...")
                results[num_examples].append(self.benchmark_pickle(examples, temp_path))
                
                self.logger.info("Benchmarking Parquet format...")
                results[num_examples].append(self.benchmark_parquet(examples, temp_path))
                
                self.logger.info("Benchmarking HDF5 format...")
                results[num_examples].append(self.benchmark_hdf5(examples, temp_path))
                
                # Benchmark SequenceStorageManager formats
                for storage_format in ['riegeli', 'tfrecord', 'pickle']:
                    self.logger.info(f"Benchmarking SequenceStorageManager with {storage_format}...")
                    result = await self.benchmark_sequence_storage_manager(examples, temp_path, storage_format)
                    results[num_examples].append(result)
        
        return results
    
    def print_results(self, results: Dict[str, List[BenchmarkResult]]):
        """Print benchmark results in a readable format."""
        print("\n" + "="*80)
        print("STORAGE FORMAT BENCHMARK RESULTS")
        print("="*80)
        
        for num_examples, benchmark_results in results.items():
            print(f"\n📊 Results for {num_examples} training examples:")
            print("-" * 60)
            
            # Sort by write performance
            valid_results = [r for r in benchmark_results if not r.error]
            valid_results.sort(key=lambda x: x.examples_per_second_write, reverse=True)
            
            # Print header
            print(f"{'Format':<20} {'Write (ex/s)':<12} {'Read (ex/s)':<12} {'Size (MB)':<10} {'Comp. Ratio':<12} {'Error':<20}")
            print("-" * 100)
            
            for result in benchmark_results:
                if result.error:
                    print(f"{result.format_name:<20} {'N/A':<12} {'N/A':<12} {'N/A':<10} {'N/A':<12} {result.error:<20}")
                else:
                    size_mb = result.file_size_bytes / (1024 * 1024)
                    print(f"{result.format_name:<20} "
                          f"{result.examples_per_second_write:<12.1f} "
                          f"{result.examples_per_second_read:<12.1f} "
                          f"{size_mb:<10.2f} "
                          f"{result.compression_ratio:<12.3f} "
                          f"{'OK':<20}")
        
        # Summary and recommendations
        print("\n" + "="*80)
        print("RECOMMENDATIONS")
        print("="*80)
        
        # Find best performers
        all_valid_results = []
        for benchmark_results in results.values():
            all_valid_results.extend([r for r in benchmark_results if not r.error])
        
        if all_valid_results:
            # Best write performance
            best_write = max(all_valid_results, key=lambda x: x.examples_per_second_write)
            print(f"🚀 Best Write Performance: {best_write.format_name} ({best_write.examples_per_second_write:.1f} examples/sec)")
            
            # Best read performance
            best_read = max(all_valid_results, key=lambda x: x.examples_per_second_read)
            print(f"📖 Best Read Performance: {best_read.format_name} ({best_read.examples_per_second_read:.1f} examples/sec)")
            
            # Best compression
            best_compression = min(all_valid_results, key=lambda x: x.compression_ratio)
            print(f"🗜️  Best Compression: {best_compression.format_name} (ratio: {best_compression.compression_ratio:.3f})")
            
            # Best overall (balanced score)
            for result in all_valid_results:
                result.balanced_score = (
                    result.examples_per_second_write * 0.4 +
                    result.examples_per_second_read * 0.4 +
                    (1 / result.compression_ratio) * 20  # Favor compression
                )
            
            best_overall = max(all_valid_results, key=lambda x: x.balanced_score)
            print(f"⭐ Best Overall: {best_overall.format_name}")
        
        print("\n💡 For sequence training data, consider:")
        print("   - Riegeli: Optimal for ML training workloads, excellent compression")
        print("   - TFRecord: Good for TensorFlow integration, reliable performance")
        print("   - Parquet: Best for analytics and metadata queries")
        print("   - HDF5: Good for scientific computing, hierarchical data")
        print("   - Pickle: Simple but limited scalability")
        
    def save_results(self, results: Dict[str, List[BenchmarkResult]], output_file: str):
        """Save benchmark results to JSON file."""
        serializable_results = {}
        
        for num_examples, benchmark_results in results.items():
            serializable_results[str(num_examples)] = []
            for result in benchmark_results:
                serializable_results[str(num_examples)].append({
                    'format_name': result.format_name,
                    'write_time_seconds': result.write_time_seconds,
                    'read_time_seconds': result.read_time_seconds,
                    'file_size_bytes': result.file_size_bytes,
                    'compression_ratio': result.compression_ratio,
                    'examples_per_second_write': result.examples_per_second_write,
                    'examples_per_second_read': result.examples_per_second_read,
                    'error': result.error
                })
        
        with open(output_file, 'w') as f:
            json.dump(serializable_results, f, indent=2)
        
        print(f"📄 Benchmark results saved to: {output_file}")


async def main():
    """Main entry point for the benchmark."""
    import argparse
    
    parser = argparse.ArgumentParser(description="Benchmark storage formats for sequence training data")
    parser.add_argument('--example-counts', nargs='+', type=int, default=[50, 100, 500],
                       help='Number of examples to benchmark with')
    parser.add_argument('--output', default='/tmp/storage_benchmark_results.json',
                       help='Output file for results')
    parser.add_argument('--debug', action='store_true', help='Enable debug logging')
    
    args = parser.parse_args()
    
    # Run benchmark
    benchmark = StorageFormatBenchmark(debug=args.debug)
    results = await benchmark.run_comprehensive_benchmark(args.example_counts)
    
    # Display and save results
    benchmark.print_results(results)
    benchmark.save_results(results, args.output)
    
    print(f"\n✅ Benchmark completed! Results saved to {args.output}")


if __name__ == "__main__":
    asyncio.run(main())