"""
Multi-Time Horizon PyTorch DataLoader for Financial Sequence Modeling

This module implements a PyTorch DataLoader that loads features from existing
ArrayRecord files generated by FeatureExtractionRunner, aligns multiple timeframes,
and generates training sequences for multi-horizon forecasting models.

Based on 2024-2025 research on:
- Temporal Fusion Transformers (TFT) with multi-horizon attention
- Hierarchical Spatio-Temporal Attention (18.4% RMSE reduction)
- Multi-Scale Self-Supervised Learning with temporal alignment
- Sparse Transformer with multi-scale attention patterns

Architecture:
    MultiTimeHorizonDataset (PyTorch Dataset)
    ├── TemporalFeatureAligner (handles time synchronization)
    ├── MultiScaleSequenceBuilder (creates hierarchical sequences)
    └── FeatureService (existing ArrayRecord reader)
"""

