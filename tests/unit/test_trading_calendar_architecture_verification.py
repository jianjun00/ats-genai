    def test_no_hardcoded_times_in_interval_timeframe_logic(self):
        """Test that interval-based timeframe logic no longer generates 1d/1w at hardcoded times."""
        print("🔍 Testing removal of hardcoded times from interval logic")
        
        # Create training callback
        callback = IntervalBasedTrainingDataCallback(
            symbols=['AAPL'],
            start_date=datetime(2025, 7, 1),
            end_date=datetime(2025, 7, 3),
            output_dir='/tmp/test_training'
        )
        
        # Test various times throughout the day
        test_times = [
            datetime(2025, 7, 1, 0, 0, 0),   # Midnight
            datetime(2025, 7, 1, 9, 30, 0),  # Market open
            datetime(2025, 7, 1, 13, 35, 0), # Afternoon (the original error time!)
            datetime(2025, 7, 1, 16, 0, 0),  # Market close
            datetime(2025, 7, 1, 23, 59, 0), # End of day
        ]
        
        for test_time in test_times:
            timeframes = callback._get_target_timeframes_for_interval(test_time)
            
            # 1d and 1w should NEVER be in interval-based timeframes now
            assert '1d' not in timeframes, f"1d should not be generated at {test_time} via intervals"
            assert '1w' not in timeframes, f"1w should not be generated at {test_time} via intervals"
            
            print(f"   ✅ {test_time}: No 1d/1w in interval timeframes: {timeframes}")
        
        print("✅ Hardcoded times removed - 1d/1w generation now purely event-driven")


