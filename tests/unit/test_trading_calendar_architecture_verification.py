    def test_runner_generates_trading_calendar_events(self, test_environment, mock_universe_manager, 
                                                    mock_universe_state_manager, mock_market_data_manager, 
                                                    mock_security_master):
        """Test that Runner generates trading_day_end and trading_week_end events."""
        print("🔍 Testing Runner trading calendar event generation")
        
        # Create runner for a single week (July 1-5, 2025 - should be Mon-Fri)
        runner = Runner(
            start_date="2025-07-01",  # Tuesday 
            end_date="2025-07-03",    # Thursday
            environment=test_environment,
            universe_id=1,
            callbacks=[],
            base_duration="5m",
            universe_manager=mock_universe_manager,
            universe_state_manager=mock_universe_state_manager,
            market_data_manager=mock_market_data_manager,
            security_master=mock_security_master,
            # NYSE trading hours: 9:30 AM - 4:00 PM ET
            trading_start_hour=9,
            trading_start_minute=30,
            trading_end_hour=16,
            trading_end_minute=0,
            timezone='America/New_York'
        )
        
        # Collect events generated by runner
        events = list(runner.iter_events())
        
        # Extract event types and times
        event_info = [(event_time, event_type) for event_time, event_type in events]
        
        print(f"📊 Generated {len(events)} events:")
        for event_time, event_type in event_info:
            print(f"   {event_type}: {event_time}")
        
        # Verify we have the expected event types
        event_types = [event_type for _, event_type in event_info]
        
        assert "start" in event_types, "Should have start event"
        assert "trading_day_end" in event_types, "Should have trading_day_end events"
        assert "interval" in event_types, "Should have interval events"
        assert "eod" in event_types, "Should have traditional eod events"
        assert "end" in event_types, "Should have end event"
        
        # Verify trading_day_end events occur at 4 PM (market close)
        trading_day_end_events = [(t, e) for t, e in event_info if e == "trading_day_end"]
        print(f"📊 Found {len(trading_day_end_events)} trading_day_end events")
        
        for event_time, _ in trading_day_end_events:
            assert event_time.hour == 16, f"Trading day end should be at 4 PM, got {event_time.hour}:00"
            assert event_time.minute == 0, f"Trading day end should be at :00, got :{event_time.minute}"
            print(f"   ✅ Trading day end at {event_time} (4:00 PM ET)")
        
        # For 3-day period (Tue-Thu), should have trading_week_end on Thursday if it's last day of week
        trading_week_end_events = [(t, e) for t, e in event_info if e == "trading_week_end"]
        print(f"📊 Found {len(trading_week_end_events)} trading_week_end events")
        
        if trading_week_end_events:
            for event_time, _ in trading_week_end_events:
                assert event_time.hour == 16, f"Trading week end should be at 4 PM, got {event_time.hour}:00"
                print(f"   ✅ Trading week end at {event_time} (4:00 PM ET)")
        
        print("✅ Runner correctly generates trading calendar events at market close times")

    @pytest.mark.asyncio
    async def test_training_callback_responds_to_trading_events(self, test_environment):
        """Test that training callback responds to trading_day_end and trading_week_end events."""
        print("🔍 Testing training callback response to trading calendar events")
        
        # Create training callback
        callback = IntervalBasedTrainingDataCallback(
            symbols=['AAPL'],
            start_date=datetime(2025, 7, 1),
            end_date=datetime(2025, 7, 3),
            output_dir='/tmp/test_training',
            storage_format='arrayrecord'
        )
        
        # Mock dependencies
        callback.training_generator = Mock()
